#!/usr/bin/env bash
# Stage what the macos-tahoe build boots from (all gitignored):
#
#   bootdisk/   the build's FAT boot disk (vmlab.wcl `disk "boot"`):
#               EFI/BOOT/BOOTx64.efi + EFI/OC/   OpenCore, the `build` config
#               com.apple.recovery.boot/         Apple's Tahoe recovery image,
#                                                which OpenCore boots as "(dmg)"
#   setup/EFI/  OpenCore with the `disk` config, which the build copies into
#               the target disk's own EFI system partition (setup/ is the
#               MACSETUP ISO; recovery.sh and the keyboard plist are tracked)
#   opencore/smbios.conf   the iMac20,1 serials, generated once with macserial
#                          and kept, so a rebuild keeps the same identity
#
# OpenCore is acidanthera's OpenCorePkg release below, pinned by version and
# sha256. opencore/mkconfig.py writes both configs from that release's own
# Sample.plist, and its ocvalidate checks them.
#
# The recovery image comes from ../iso/fetch-macos-tahoe.sh (Apple's Internet
# Recovery, verified against Apple's signed chunklist), cached in ../iso/.
#
# Needs: curl, unzip, python3, openssl (and what fetch-macos-tahoe.sh needs).
set -euo pipefail
cd "$(dirname "$0")"

OC_VERSION=1.0.8
OC_SHA256=2011e8b7216ecb2645d97ea710df965947edd406846e92050b9bc4190be6d27b
OC_URL="https://github.com/acidanthera/OpenCorePkg/releases/download/$OC_VERSION/OpenCore-$OC_VERSION-RELEASE.zip"
OC_ZIP="${OC_ZIP:-/tmp/vmlab-fetch/OpenCore-$OC_VERSION-RELEASE.zip}"
SMBIOS_MODEL=iMac20,1

# The recovery image. The raw conversion is for attaching it as a disk by
# hand; this template boots the DMG through OpenCore and needs none.
NO_IMG=1 ../iso/fetch-macos-tahoe.sh
DMG=../iso/macos-tahoe-recovery.dmg
CNK=../iso/macos-tahoe-recovery.chunklist

if [[ ! -f "$OC_ZIP" ]] || ! echo "$OC_SHA256  $OC_ZIP" | sha256sum -c --quiet - 2>/dev/null; then
    mkdir -p "$(dirname "$OC_ZIP")"
    echo "downloading OpenCore $OC_VERSION..."
    curl -fSL --retry 3 -o "$OC_ZIP" "$OC_URL"
    echo "$OC_SHA256  $OC_ZIP" | sha256sum -c --quiet - \
        || { echo "OpenCore-$OC_VERSION-RELEASE.zip failed its checksum" >&2; exit 1; }
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
unzip -q "$OC_ZIP" -d "$tmp"
chmod +x "$tmp/Utilities/macserial/macserial.linux" "$tmp/Utilities/ocvalidate/ocvalidate.linux"

if [[ ! -s opencore/smbios.conf ]]; then
    # macserial prints "<serial> | <board serial>" for a model.
    line=$("$tmp/Utilities/macserial/macserial.linux" -m "$SMBIOS_MODEL" -n 1 2>/dev/null)
    serial=${line%% | *}
    mlb=${line##* | }
    [[ -n "$serial" && -n "$mlb" && "$serial" != "$line" ]] \
        || { echo "macserial gave no serial for $SMBIOS_MODEL: $line" >&2; exit 1; }
    {
        echo "# Generated by fetch-deps.sh with OpenCore $OC_VERSION's macserial."
        echo "model=$SMBIOS_MODEL"
        echo "serial=$serial"
        echo "mlb=$mlb"
        echo "uuid=$(python3 -c 'import uuid; print(str(uuid.uuid4()).upper())')"
        echo "rom=$(openssl rand -hex 6)"
    } > opencore/smbios.conf
    echo "smbios: generated $SMBIOS_MODEL serial $serial"
fi

stage_efi() {
    local dest=$1 variant=$2
    rm -rf "$dest/EFI"
    mkdir -p "$dest/EFI/BOOT" "$dest/EFI/OC/Drivers"
    cp "$tmp/X64/EFI/BOOT/BOOTx64.efi" "$dest/EFI/BOOT/"
    cp "$tmp/X64/EFI/OC/OpenCore.efi" "$dest/EFI/OC/"
    cp "$tmp/X64/EFI/OC/Drivers/OpenRuntime.efi" "$tmp/X64/EFI/OC/Drivers/OpenHfsPlus.efi" \
        "$dest/EFI/OC/Drivers/"
    python3 opencore/mkconfig.py "$tmp/Docs/Sample.plist" "$dest/EFI/OC/config.plist" \
        --variant "$variant" --smbios opencore/smbios.conf
    "$tmp/Utilities/ocvalidate/ocvalidate.linux" "$dest/EFI/OC/config.plist" >"$tmp/ocvalidate.log" 2>&1 \
        || { cat "$tmp/ocvalidate.log" >&2; echo "ocvalidate rejected the $variant config" >&2; exit 1; }
    echo "opencore: $variant config -> $dest/EFI/OC/config.plist (ocvalidate clean)"
}

mkdir -p bootdisk
stage_efi bootdisk build
stage_efi setup disk

# The recovery image under the name OpenCore looks for. A hard link where
# the checkout and ../iso share a filesystem, else a copy (~1 GB).
rec=bootdisk/com.apple.recovery.boot
mkdir -p "$rec"
for pair in "$DMG:RecoveryImage.dmg" "$CNK:RecoveryImage.chunklist"; do
    src=${pair%%:*} dst="$rec/${pair#*:}"
    if [[ ! "$dst" -ef "$src" ]]; then
        rm -f "$dst"
        ln "$src" "$dst" 2>/dev/null || cp "$src" "$dst"
    fi
done
echo "recovery: $(du -shL "$rec" | cut -f1) staged in $rec"
