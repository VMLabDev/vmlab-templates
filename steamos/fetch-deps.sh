#!/bin/sh
# Stage disk/steamos.qcow2: SteamOS installed the way a Steam Deck gets it,
# by Valve's own recovery image, ready for `vmlab template build` to import.
#
# Valve publishes SteamOS only as a recovery image: a live system whose
# "Wipe Device & Install SteamOS" action (repair_device.sh) images an A/B
# partition layout onto the Deck's NVMe drive. vmlab cannot attach a raw image
# beside a template build's disk, so this script does the install itself in
# a throwaway lab: the recovery image boots read-only (snapshot=on) beside a
# blank target qcow2, installer/install.ws drives the console, and
# installer/payload/install.sh runs repair_device.sh against the target and
# bakes in a first-boot unit that installs vmlab-agent from the build's VMLAB
# ISO. The lab is destroyed afterwards; only the target disk is kept.
#
# Needs vmlab on PATH, qemu-img, bzip2, KVM, and Docker (for venus/build.sh).
# Takes about ten minutes plus the 3.1G download.
set -eu

VERSION="20260707.10-3.8.14"
ARCHIVE="steamdeck-oobe-repair-${VERSION}.img.bz2"
URL="https://steamdeck-images.steamos.cloud/recovery/${ARCHIVE}"
SHA256="4254ee02ec34ae8add9aceef1881a2ce675a9d0176171df92e0eaa1bf014c594"
DISK_SIZE="128G"

cd "$(dirname "$0")"
here="$(pwd)"
mkdir -p disk

# The Venus driver the provision installs (venus/build.sh says why). It has
# its own up-to-date check, so it runs even when the disk is already staged.
./venus/build.sh

if [ -f disk/steamos.qcow2 ]; then
    echo "disk/steamos.qcow2 already staged"
    exit 0
fi

if [ ! -f disk/steamos-repair.img ]; then
    if [ ! -f "disk/${ARCHIVE}" ]; then
        echo "downloading ${URL} ..."
        curl -L --fail -o "disk/${ARCHIVE}.part" "$URL"
        mv "disk/${ARCHIVE}.part" "disk/${ARCHIVE}"
    fi
    echo "${SHA256}  disk/${ARCHIVE}" | sha256sum -c -
    echo "decompressing ..."
    bzip2 -dc "disk/${ARCHIVE}" > disk/steamos-repair.img.part
    mv disk/steamos-repair.img.part disk/steamos-repair.img
    # The archive stays as a cache: re-staging after a failed install skips the download.
fi

rm -f disk/steamos.qcow2.part
qemu-img create -q -f qcow2 disk/steamos.qcow2.part "$DISK_SIZE"

lab="$(mktemp -d "$here/disk/install-lab.XXXXXX")"
cleanup() {
    if [ -f "$lab/install-failed.png" ]; then
        mv "$lab/install-failed.png" disk/install-failed.png
        echo "the install VM's last screen is in disk/install-failed.png" >&2
    fi
    (cd "$lab" && vmlab destroy >/dev/null 2>&1) || true
    rm -rf "$lab"
}
trap cleanup EXIT INT TERM

cp -r installer/payload "$lab/payload"
cp installer/install.ws "$lab/install.ws"
cat > "$lab/vmlab.wcl" <<EOF
import <vmlab.wcl>

// Generated by steamos/fetch-deps.sh; deleted when it finishes.
lab "steamos-install" {
  vm "installer" {
    template = "scratch"
    arch     = "x86_64"
    profile  = "linux-modern"
    disk     = 1GiB
    cpus     = 4
    memory   = 8GiB
    media { kind = "iso" from = "./payload/" label = "STEAMINST" }
    qemu_args = [
      "-drive", "file=$here/disk/steamos-repair.img,format=raw,if=none,id=recovery,snapshot=on",
      "-device", "virtio-blk-pci,drive=recovery,bootindex=0",
      "-drive", "file=$here/disk/steamos.qcow2.part,format=qcow2,if=none,id=target",
      "-device", "virtio-blk-pci,drive=target,serial=steamos-target",
    ]
  }
}
EOF

echo "installing SteamOS in a throwaway lab ($lab) ..."
(cd "$lab" && vmlab up && vmlab script install.ws)

mv disk/steamos.qcow2.part disk/steamos.qcow2
rm -f disk/steamos-repair.img
echo "staged disk/steamos.qcow2"
